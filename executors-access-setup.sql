-- Dyserrealm Script: role-based access for EXECUTORS directory
-- Run this entire file in Supabase Dashboard -> SQL Editor.
-- Then replace YOUR_ACCOUNT_EMAIL@example.com with the email used by your site account
-- and run the final INSERT statement at the bottom.

create table if not exists public.site_roles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null check (role in ('creator', 'admin'))
);

alter table public.site_roles enable row level security;

drop policy if exists "Users can read their own site role" on public.site_roles;
create policy "Users can read their own site role"
  on public.site_roles for select to authenticated
  using (auth.uid() = user_id);

grant select on public.site_roles to authenticated;

create table if not exists public.executors (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(trim(name)) between 2 and 80),
  platform text not null check (platform in ('roblox', 'pc', 'roblox pc')),
  description text not null check (char_length(trim(description)) between 5 and 600),
  version text not null default 'See official website' check (char_length(version) <= 80),
  official_url text not null check (official_url ~* '^https?://'),
  created_by uuid not null references auth.users(id) on delete restrict,
  created_at timestamptz not null default now()
);

create index if not exists executors_created_at_idx
  on public.executors (created_at desc);

alter table public.executors enable row level security;

drop policy if exists "Anyone can view executors" on public.executors;
create policy "Anyone can view executors"
  on public.executors for select
  using (true);

drop policy if exists "Creators and admins can add executors" on public.executors;
create policy "Creators and admins can add executors"
  on public.executors for insert to authenticated
  with check (
    auth.uid() = created_by
    and exists (
      select 1 from public.site_roles r
      where r.user_id = auth.uid()
        and r.role in ('creator', 'admin')
    )
  );

grant select on public.executors to anon, authenticated;
grant insert on public.executors to authenticated;
grant usage, select on sequence public.executors_id_seq to authenticated;

