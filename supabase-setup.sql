create table if not exists public.posts (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 1 and 100),
  body text not null check (char_length(body) between 1 and 8000),
  category text not null default 'Ideas' check (category in ('Technology','Guides','Ideas','Updates')),
  author_id uuid not null references auth.users(id) on delete cascade,
  author_name text not null default 'Realm member' check (char_length(author_name) between 1 and 32),
  created_at timestamptz not null default now()
);
alter table public.posts enable row level security;
drop policy if exists "Anyone can read posts" on public.posts;
create policy "Anyone can read posts" on public.posts for select using (true);
drop policy if exists "Signed-in users can publish their own posts" on public.posts;
create policy "Signed-in users can publish their own posts" on public.posts for insert to authenticated with check (auth.uid() = author_id);
drop policy if exists "Authors can update their own posts" on public.posts;
create policy "Authors can update their own posts" on public.posts for update to authenticated using (auth.uid() = author_id) with check (auth.uid() = author_id);
drop policy if exists "Authors can delete their own posts" on public.posts;
create policy "Authors can delete their own posts" on public.posts for delete to authenticated using (auth.uid() = author_id);
grant select on public.posts to anon, authenticated;
grant insert, update, delete on public.posts to authenticated;
grant usage, select on sequence public.posts_id_seq to authenticated;
