create table if not exists public.posts (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 1 and 100),
  body text not null check (char_length(body) between 1 and 8000),
  category text not null default 'Ideas' check (category in ('Technology','Guides','Ideas','Updates')),
  author_id uuid not null references auth.users(id) on delete cascade,
  author_name text not null default 'Realm member' check (char_length(author_name) between 1 and 32),
  created_at timestamptz not null default now()
);
alter table public.posts enable row level security;
drop policy if exists "Anyone can read posts" on public.posts;
create policy "Anyone can read posts" on public.posts for select using (true);
drop policy if exists "Signed-in users can publish their own posts" on public.posts;
create policy "Signed-in users can publish their own posts" on public.posts for insert to authenticated with check (auth.uid() = author_id);
drop policy if exists "Authors can update their own posts" on public.posts;
create policy "Authors can update their own posts" on public.posts for update to authenticated using (auth.uid() = author_id) with check (auth.uid() = author_id);
drop policy if exists "Authors can delete their own posts" on public.posts;
create policy "Authors can delete their own posts" on public.posts for delete to authenticated using (auth.uid() = author_id);
grant select on public.posts to anon, authenticated;
grant insert, update, delete on public.posts to authenticated;
grant usage, select on sequence public.posts_id_seq to authenticated;

-- Marketplace listings
create table if not exists public.sales (
 id bigint generated by default as identity primary key,
 title text not null check (char_length(title) between 1 and 90),
 description text not null check (char_length(description) between 1 and 3000),
 price text not null check (char_length(price) between 1 and 40),
 image_url text not null,
 image_path text not null,
 seller_id uuid not null references auth.users(id) on delete cascade,
 seller_name text not null default 'Realm seller' check (char_length(seller_name) between 1 and 32),
 created_at timestamptz not null default now()
);
alter table public.sales enable row level security;
drop policy if exists "Anyone can view sales" on public.sales;
create policy "Anyone can view sales" on public.sales for select using (true);
drop policy if exists "Signed in sellers can create listings" on public.sales;
create policy "Signed in sellers can create listings" on public.sales for insert to authenticated with check (auth.uid() = seller_id);
drop policy if exists "Sellers can update their own listings" on public.sales;
create policy "Sellers can update their own listings" on public.sales for update to authenticated using (auth.uid() = seller_id) with check (auth.uid() = seller_id);
drop policy if exists "Sellers can delete their own listings" on public.sales;
create policy "Sellers can delete their own listings" on public.sales for delete to authenticated using (auth.uid() = seller_id);
grant select on public.sales to anon, authenticated;
grant insert, update, delete on public.sales to authenticated;
grant usage, select on sequence public.sales_id_seq to authenticated;

-- Public image bucket for marketplace listings (max 5 MB, images only).
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('product-images', 'product-images', true, 5242880, array['image/png','image/jpeg','image/webp','image/gif'])
on conflict (id) do update set public = true, file_size_limit = 5242880, allowed_mime_types = array['image/png','image/jpeg','image/webp','image/gif'];
drop policy if exists "Anyone can view product images" on storage.objects;
create policy "Anyone can view product images" on storage.objects for select using (bucket_id = 'product-images');
drop policy if exists "Users upload own product images" on storage.objects;
create policy "Users upload own product images" on storage.objects for insert to authenticated with check (bucket_id = 'product-images' and (storage.foldername(name))[1] = auth.uid()::text);
drop policy if exists "Users update own product images" on storage.objects;
create policy "Users update own product images" on storage.objects for update to authenticated using (bucket_id = 'product-images' and (storage.foldername(name))[1] = auth.uid()::text) with check (bucket_id = 'product-images' and (storage.foldername(name))[1] = auth.uid()::text);
drop policy if exists "Users delete own product images" on storage.objects;
create policy "Users delete own product images" on storage.objects for delete to authenticated using (bucket_id = 'product-images' and (storage.foldername(name))[1] = auth.uid()::text);
