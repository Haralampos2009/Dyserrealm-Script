-- Dyserrealm Script: comments + account profile settings
-- Run once in Supabase Dashboard -> SQL Editor.
-- The frontend uses the existing public.scripts table.

create table if not exists public.script_comments (
  id bigint generated by default as identity primary key,
  script_id bigint not null references public.scripts(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  author_name text not null default 'Realm member',
  body text not null check (char_length(trim(body)) between 1 and 2000),
  created_at timestamptz not null default now()
);

create index if not exists script_comments_script_created_idx
  on public.script_comments (script_id, created_at);

alter table public.script_comments enable row level security;

drop policy if exists "Anyone can read script comments" on public.script_comments;
create policy "Anyone can read script comments"
  on public.script_comments for select using (true);

drop policy if exists "Signed-in users can add their own comments" on public.script_comments;
create policy "Signed-in users can add their own comments"
  on public.script_comments for insert to authenticated
  with check (auth.uid() = user_id);

drop policy if exists "Users can update their own comments" on public.script_comments;
create policy "Users can update their own comments"
  on public.script_comments for update to authenticated
  using (auth.uid() = user_id) with check (auth.uid() = user_id);

drop policy if exists "Users can delete their own comments" on public.script_comments;
create policy "Users can delete their own comments"
  on public.script_comments for delete to authenticated
  using (auth.uid() = user_id);

grant select on public.script_comments to anon, authenticated;
grant insert, update, delete on public.script_comments to authenticated;
grant usage, select on sequence public.script_comments_id_seq to authenticated;
