-- Dyserrealm Script: account bans and warning escalation.
-- Safe to run again in Supabase SQL Editor after the previous ban setup.
create table if not exists public.site_bans (
  user_id uuid primary key references auth.users(id) on delete cascade,
  ban_until timestamptz null,
  reason text,
  created_by uuid not null references auth.users(id),
  created_at timestamptz not null default now()
);
alter table public.site_bans enable row level security;
revoke all on public.site_bans from anon, authenticated;

create table if not exists public.site_warnings (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  reason text not null,
  issued_by uuid not null references auth.users(id),
  created_at timestamptz not null default now()
);
alter table public.site_warnings enable row level security;
revoke all on public.site_warnings from anon, authenticated;

create table if not exists public.site_moderation_state (
  user_id uuid primary key references auth.users(id) on delete cascade,
  warning_count integer not null default 0 check (warning_count between 0 and 2),
  ban_level integer not null default 0 check (ban_level >= 0),
  updated_at timestamptz not null default now()
);
alter table public.site_moderation_state enable row level security;
revoke all on public.site_moderation_state from anon, authenticated;

create or replace function public.check_my_site_ban()
returns table (is_banned boolean, ban_until timestamptz, reason text)
language sql security definer set search_path = ''
as $$
  select
    (b.user_id is not null and (b.ban_until is null or b.ban_until > now())) as is_banned,
    case when b.user_id is not null and (b.ban_until is null or b.ban_until > now()) then b.ban_until else null end,
    case when b.user_id is not null and (b.ban_until is null or b.ban_until > now()) then b.reason else null end
  from (select auth.uid() as uid) u
  left join public.site_bans b on b.user_id = u.uid;
$$;

create or replace function public.creator_list_site_bans()
returns table (user_id uuid, email text, ban_until timestamptz, reason text)
language plpgsql security definer set search_path = ''
as $$
begin
  if not exists (select 1 from public.site_roles sr where sr.user_id = auth.uid() and sr.role in ('creator','admin')) then
    raise exception 'Creator or admin role required';
  end if;
  return query
    select b.user_id, au.email::text, b.ban_until, b.reason
    from public.site_bans b join auth.users au on au.id = b.user_id
    where b.ban_until is null or b.ban_until > now()
    order by b.created_at desc;
end;
$$;

create or replace function public.creator_set_site_ban(target_email text, duration_minutes integer, ban_reason text default null)
returns void
language plpgsql security definer set search_path = ''
as $$
declare
  caller_role text;
  target_id uuid;
  target_role text;
  until_time timestamptz;
begin
  select sr.role into caller_role from public.site_roles sr where sr.user_id = auth.uid();
  if caller_role not in ('creator','admin') then raise exception 'Creator or admin role required'; end if;
  select au.id into target_id from auth.users au where lower(au.email) = lower(trim(target_email)) limit 1;
  if target_id is null then raise exception 'No registered account found with that email'; end if;
  if target_id = auth.uid() then raise exception 'You cannot ban your own account'; end if;
  select sr.role into target_role from public.site_roles sr where sr.user_id = target_id;
  if caller_role = 'admin' and target_role in ('creator','admin') then raise exception 'Admins cannot ban creators or admins'; end if;
  if duration_minutes = 0 then
    delete from public.site_bans where user_id = target_id;
    return;
  end if;
  if duration_minutes is not null and duration_minutes not in (60,1440,10080,43200) then raise exception 'Invalid ban duration'; end if;
  if duration_minutes is null then until_time := null; else until_time := now() + make_interval(mins => duration_minutes); end if;
  insert into public.site_bans(user_id,ban_until,reason,created_by)
  values(target_id,until_time,left(coalesce(ban_reason,''),300),auth.uid())
  on conflict(user_id) do update set ban_until=excluded.ban_until,reason=excluded.reason,created_by=excluded.created_by,created_at=now();
end;
$$;

create or replace function public.creator_list_site_warnings()
returns table (user_id uuid, email text, warning_count integer, ban_level integer, next_ban_label text, latest_reason text)
language plpgsql security definer set search_path = ''
as $$
begin
  if not exists (select 1 from public.site_roles sr where sr.user_id = auth.uid() and sr.role in ('creator','admin')) then
    raise exception 'Creator or admin role required';
  end if;
  return query
    select st.user_id, au.email::text, st.warning_count, st.ban_level,
      case when st.ban_level = 0 then '1 DAY'
           when st.ban_level = 1 then '7 DAYS'
           when st.ban_level = 2 then '30 DAYS'
           else 'PERMANENT' end,
      (select w.reason from public.site_warnings w where w.user_id = st.user_id order by w.created_at desc limit 1)
    from public.site_moderation_state st
    join auth.users au on au.id = st.user_id
    order by st.updated_at desc;
end;
$$;

create or replace function public.creator_issue_site_warning(target_email text, warning_reason text)
returns table (warning_count integer, ban_level integer, auto_banned boolean, ban_until timestamptz)
language plpgsql security definer set search_path = ''
as $$
declare
  caller_role text;
  target_id uuid;
  target_role text;
  current_count integer;
  current_level integer;
  new_until timestamptz;
  new_reason text;
begin
  select sr.role into caller_role from public.site_roles sr where sr.user_id = auth.uid();
  if caller_role not in ('creator','admin') then raise exception 'Creator or admin role required'; end if;
  select au.id into target_id from auth.users au where lower(au.email) = lower(trim(target_email)) limit 1;
  if target_id is null then raise exception 'No registered account found with that email'; end if;
  if target_id = auth.uid() then raise exception 'You cannot warn your own account'; end if;
  select sr.role into target_role from public.site_roles sr where sr.user_id = target_id;
  if caller_role = 'admin' and target_role in ('creator','admin') then raise exception 'Admins cannot warn creators or admins'; end if;
  new_reason := left(trim(coalesce(warning_reason,'')),300);
  if new_reason = '' then raise exception 'A warning reason is required'; end if;

  insert into public.site_moderation_state(user_id) values(target_id) on conflict(user_id) do nothing;
  select st.warning_count, st.ban_level into current_count, current_level
    from public.site_moderation_state st where st.user_id = target_id for update;
  insert into public.site_warnings(user_id,reason,issued_by) values(target_id,new_reason,auth.uid());

  current_count := current_count + 1;
  if current_count < 3 then
    update public.site_moderation_state set warning_count=current_count, updated_at=now() where user_id=target_id;
    return query select current_count, current_level, false, null::timestamptz;
    return;
  end if;

  if current_level = 0 then new_until := now() + interval '1 day';
  elsif current_level = 1 then new_until := now() + interval '7 days';
  elsif current_level = 2 then new_until := now() + interval '30 days';
  else new_until := null;
  end if;

  insert into public.site_bans(user_id,ban_until,reason,created_by)
  values(target_id,new_until,'Automatic ban after 3 warnings: ' || new_reason,auth.uid())
  on conflict(user_id) do update set ban_until=excluded.ban_until,reason=excluded.reason,created_by=excluded.created_by,created_at=now();

  update public.site_moderation_state
    set warning_count=0, ban_level=current_level+1, updated_at=now()
    where user_id=target_id;
  return query select 0, current_level+1, true, new_until;
end;
$$;

revoke all on function public.check_my_site_ban() from public, anon;
revoke all on function public.creator_list_site_bans() from public, anon;
revoke all on function public.creator_set_site_ban(text,integer,text) from public, anon;
revoke all on function public.creator_list_site_warnings() from public, anon;
revoke all on function public.creator_issue_site_warning(text,text) from public, anon;
grant execute on function public.check_my_site_ban() to authenticated;
grant execute on function public.creator_list_site_bans() to authenticated;
grant execute on function public.creator_set_site_ban(text,integer,text) to authenticated;
grant execute on function public.creator_list_site_warnings() to authenticated;
grant execute on function public.creator_issue_site_warning(text,text) to authenticated;
